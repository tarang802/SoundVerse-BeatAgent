"""Part 3 playback: Score -> one self-contained HTML page that plays it with Web Audio.

The page is generated by CODE from a fixed template; the LLM never writes JavaScript
(generated code running in a user's browser could do anything -- a fixed, reviewed
template with the score as inert JSON data cannot). Properties checked by
evals/part3_render.py:
  * synthesis only: oscillators, filtered noise, envelopes; no audio from the original
  * no network: a Content-Security-Policy of default-src 'none' makes the browser refuse
    every request; no external scripts, fonts or assets
  * play / stop, seamless loop: notes are scheduled by exact arithmetic
    (loop start + n x loop length + beat x seconds-per-beat) with a look-ahead
    scheduler, so loops cannot drift
  * per-track mixer (level, mute) and tempo control
  * window.renderOffline(seconds) runs the SAME scheduling code in an
    OfflineAudioContext, so the measured render is what the page plays
"""
from __future__ import annotations

import json

from .score import Score

TEMPLATE = r"""<!doctype html>
<html lang="en"><head><meta charset="utf-8">
<meta http-equiv="Content-Security-Policy" content="default-src 'none'; script-src 'unsafe-inline'; style-src 'unsafe-inline'">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>__TITLE__ - Beat Agent recreation</title>
<style>
body{margin:0;background:#0b0b0d;color:#e8e8ea;font:14px/1.4 system-ui,Segoe UI,sans-serif}
main{max-width:760px;margin:0 auto;padding:20px 16px}
h1{font-size:18px;margin:0 0 4px}.sub{color:#9a9aa3;margin:0 0 16px}
button{background:#1e1e24;color:#e8e8ea;border:1px solid #33333d;border-radius:6px;padding:8px 18px;font-size:14px;cursor:pointer}
button.on{background:#c6ff3d;color:#0b0b0d;border-color:#c6ff3d}
.row{display:flex;gap:10px;align-items:center;flex-wrap:wrap;margin:10px 0}
.trk{display:grid;grid-template-columns:110px 1fr 70px 60px;gap:10px;align-items:center;padding:6px 0;border-top:1px solid #1f1f26}
input[type=range]{width:100%}input[type=number]{width:70px;background:#16161b;color:#e8e8ea;border:1px solid #33333d;border-radius:4px;padding:4px}
.small{color:#7d7d86;font-size:12px}
</style></head><body><main>
<h1>__TITLE__</h1>
<p class="sub" id="info"></p>
<div class="row"><button id="play">Play</button><button id="stop">Stop</button>
<label>Tempo <input type="number" id="tempo" min="30" max="300" step="0.1"> BPM</label>
<span class="small" id="pos"></span></div>
<div id="mixer"></div>
<p class="small">Everything you hear is synthesised in your browser from the score below (oscillators,
filtered noise, envelopes). No audio from the original recording is embedded, and this page makes no
network requests. Notes were measured from the audio by signal analysis and a transcription model.</p>
<script id="score" type="application/json">__SCORE__</script>
<script>
"use strict";
const SCORE = JSON.parse(document.getElementById("score").textContent);
const DRUM = {36: "kick", 38: "snare", 42: "hat", 46: "openhat"};
let tempo = SCORE.tempo_bpm;
const mix = {};                                        // track name -> {db, mute}
for (const t of SCORE.tracks) mix[t.name] = {db: t.gain_db, mute: t.mute};

function mtof(p) { return 440 * Math.pow(2, (p - 69) / 12); }
function dbToGain(db) { return Math.pow(10, db / 20); }

function noiseBuffer(ctx) {                            // seeded: offline renders are reproducible
  const n = Math.floor(ctx.sampleRate * 1.0), b = ctx.createBuffer(1, n, ctx.sampleRate), d = b.getChannelData(0);
  let s = 12345;
  for (let i = 0; i < n; i++) { s = (1103515245 * s + 12345) >>> 0; d[i] = (s / 2147483648) - 1; }
  return b;
}

// one graph per context: track gains -> master -> destination
function buildGraph(ctx) {
  const master = ctx.createGain(); master.gain.value = 0.8;
  const comp = ctx.createDynamicsCompressor(); comp.threshold.value = -10; comp.ratio.value = 4;
  master.connect(comp).connect(ctx.destination);
  const tracks = {};
  for (const t of SCORE.tracks) {
    const g = ctx.createGain(); g.connect(master); tracks[t.name] = g;
  }
  const graph = {ctx, master, tracks, noise: noiseBuffer(ctx)};
  applyMix(graph);
  return graph;
}
function applyMix(graph) {
  for (const t of SCORE.tracks) {
    const m = mix[t.name];
    graph.tracks[t.name].gain.setValueAtTime(m.mute ? 0 : dbToGain(m.db), graph.ctx.currentTime);
  }
}

function drum(graph, dest, kind, when, vel) {
  const ctx = graph.ctx, out = ctx.createGain();
  out.connect(dest);
  if (kind === "kick") {
    const o = ctx.createOscillator(); o.type = "sine";
    o.frequency.setValueAtTime(150, when); o.frequency.exponentialRampToValueAtTime(45, when + 0.08);
    out.gain.setValueAtTime(vel, when); out.gain.exponentialRampToValueAtTime(0.001, when + 0.35);
    o.connect(out); o.start(when); o.stop(when + 0.4);
  } else {
    const src = ctx.createBufferSource(); src.buffer = graph.noise;
    const f = ctx.createBiquadFilter();
    let len = 0.05, level = vel * 0.5;
    if (kind === "snare") { f.type = "bandpass"; f.frequency.value = 2500; f.Q.value = 0.7; len = 0.18; level = vel * 0.9;
      const tone = ctx.createOscillator(), tg = ctx.createGain(); tone.type = "triangle"; tone.frequency.value = 185;
      tg.gain.setValueAtTime(vel * 0.6, when); tg.gain.exponentialRampToValueAtTime(0.001, when + 0.08);
      tone.connect(tg).connect(out); tone.start(when); tone.stop(when + 0.1);
    } else { f.type = "highpass"; f.frequency.value = 7000; if (kind === "openhat") len = 0.3; }
    const ng = ctx.createGain();
    ng.gain.setValueAtTime(level, when); ng.gain.exponentialRampToValueAtTime(0.001, when + len);
    src.connect(f).connect(ng).connect(out); src.start(when, (when * 7.3) % 0.5); src.stop(when + len + 0.02);
    out.gain.value = 1;
  }
}

function tone(graph, track, note, when, dur) {
  const ctx = graph.ctx, p = track.patch, vel = Math.pow(note.velocity / 127, 1.5);
  const o = ctx.createOscillator(), f = ctx.createBiquadFilter(), g = ctx.createGain();
  o.type = p.wave; o.frequency.value = mtof(note.pitch);
  f.type = "lowpass"; f.frequency.value = p.cutoff_hz; f.Q.value = p.resonance;
  const a = p.attack_s, d = p.decay_s, s = p.sustain, r = p.release_s, peak = vel * 0.35;
  g.gain.setValueAtTime(0, when);
  g.gain.linearRampToValueAtTime(peak, when + a);
  g.gain.setTargetAtTime(peak * s, when + a, d / 3);
  const end = when + Math.max(dur, a + 0.01);
  g.gain.cancelAndHoldAtTime ? g.gain.cancelAndHoldAtTime(end) : g.gain.setValueAtTime(peak * s, end);
  g.gain.setTargetAtTime(0, end, r / 3);
  o.connect(f).connect(g).connect(graph.tracks[track.name]);
  o.start(when); o.stop(end + r * 2 + 0.05);
}

// every note of one loop pass, starting at absolute context time t0
function scheduleLoop(graph, t0) {
  const spb = 60 / tempo; let n = 0;
  for (const t of SCORE.tracks) {
    for (const note of t.notes) {
      const when = t0 + note.start * spb;
      if (t.kind === "drums") drum(graph, graph.tracks[t.name], DRUM[note.pitch] || "hat", when, Math.pow(note.velocity / 127, 1.2));
      else tone(graph, t, note, when, note.duration * spb);
      n++;
    }
  }
  return n;
}
function loopSeconds() { return SCORE.loop_beats * 60 / tempo; }

// ---- live playback: look-ahead scheduler (exact loop arithmetic, no drift)
let live = null;
const state = window.__beatagent = {playing: false, loopsScheduled: 0, notesScheduled: 0};
function play() {
  if (live) return;
  const ctx = new (window.AudioContext || window.webkitAudioContext)();
  const graph = buildGraph(ctx);
  const start = ctx.currentTime + 0.1;
  let next = 0;
  const tick = () => {
    while (start + next * loopSeconds() < ctx.currentTime + 0.25) {
      state.notesScheduled += scheduleLoop(graph, start + next * loopSeconds());
      next++; state.loopsScheduled = next;
    }
    const pos = ((ctx.currentTime - start) % loopSeconds()) / (60 / tempo);
    document.getElementById("pos").textContent = pos >= 0 ? `bar ${Math.floor(pos / SCORE.beats_per_bar) + 1}.${Math.floor(pos % SCORE.beats_per_bar) + 1}` : "";
  };
  tick();
  live = {ctx, graph, timer: setInterval(tick, 25)};
  state.playing = true;
  document.getElementById("play").classList.add("on");
}
function stop() {
  if (!live) return;
  clearInterval(live.timer);
  const {ctx, graph} = live;
  graph.master.gain.setTargetAtTime(0, ctx.currentTime, 0.01);
  setTimeout(() => ctx.close(), 100);
  live = null; state.playing = false;
  document.getElementById("play").classList.remove("on");
  document.getElementById("pos").textContent = "";
}

// ---- offline render for evals: same scheduling code, OfflineAudioContext
window.renderOffline = async function (seconds, sampleRate) {
  sampleRate = sampleRate || 44100;
  const ctx = new OfflineAudioContext(2, Math.ceil(seconds * sampleRate), sampleRate);
  const graph = buildGraph(ctx);
  for (let k = 0; k * loopSeconds() < seconds; k++) scheduleLoop(graph, k * loopSeconds());
  const buf = await ctx.startRendering();
  const L = buf.getChannelData(0), R = buf.getChannelData(1), n = L.length;
  const pcm = new Int16Array(n * 2);
  for (let i = 0; i < n; i++) {
    pcm[2 * i] = Math.max(-1, Math.min(1, L[i])) * 32767;
    pcm[2 * i + 1] = Math.max(-1, Math.min(1, R[i])) * 32767;
  }
  const bytes = new Uint8Array(pcm.buffer); let bin = "";
  for (let i = 0; i < bytes.length; i += 0x8000) bin += String.fromCharCode.apply(null, bytes.subarray(i, i + 0x8000));
  return {sampleRate, channels: 2, frames: n, pcm16: btoa(bin)};
};

// ---- UI
document.getElementById("play").onclick = play;
document.getElementById("stop").onclick = stop;
const tin = document.getElementById("tempo");
tin.value = tempo.toFixed(1);
tin.onchange = () => { const v = parseFloat(tin.value); if (v >= 30 && v <= 300) { const was = !!live; stop(); tempo = v; if (was) play(); } };
document.getElementById("info").textContent =
  `${SCORE.tempo_bpm.toFixed(1)} BPM, ${SCORE.time_signature}, ${SCORE.bars} bars loop, ` +
  SCORE.tracks.map(t => `${t.name} (${t.notes.length} notes)`).join(", ");
const mixer = document.getElementById("mixer");
for (const t of SCORE.tracks) {
  const row = document.createElement("div"); row.className = "trk";
  row.innerHTML = `<span>${t.name}</span><input type="range" min="-30" max="6" step="0.5" value="${t.gain_db}">` +
                  `<span class="small">${t.gain_db.toFixed(1)} dB</span><label><input type="checkbox" ${t.mute ? "checked" : ""}> mute</label>`;
  const [slider, label, box] = [row.querySelector("input[type=range]"), row.querySelector(".small"), row.querySelector("input[type=checkbox]")];
  slider.oninput = () => { mix[t.name].db = parseFloat(slider.value); label.textContent = `${mix[t.name].db.toFixed(1)} dB`; if (live) applyMix(live.graph); };
  box.onchange = () => { mix[t.name].mute = box.checked; if (live) applyMix(live.graph); };
  mixer.appendChild(row);
}
// embedded in the app (a sandboxed iframe, so the app cannot look inside): say we loaded
if (window.parent !== window) {
  window.parent.postMessage({beatagent: "ready", tracks: SCORE.tracks.length, notes:
    SCORE.tracks.reduce((n, t) => n + t.notes.length, 0)}, "*");
}
</script></main></body></html>
"""


def render_html(score: Score, title: str | None = None) -> str:
    """The page for a score. The score is embedded as JSON data (with '</' escaped so it
    cannot close the script element), never as code."""
    data = score.model_dump_json().replace("</", "<\\/")
    name = title or score.source.get("name", "Recreation")
    safe_title = "".join(ch for ch in str(name) if ch.isalnum() or ch in " -_.()")[:80] or "Recreation"
    return TEMPLATE.replace("__TITLE__", safe_title).replace("__SCORE__", data)


def write_page(score: Score, path, title: str | None = None) -> None:
    from pathlib import Path
    Path(path).write_text(render_html(score, title), encoding="utf-8")
