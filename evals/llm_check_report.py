"""Prompt -> output report for a chat-suite run.

    python -m evals.llm_check_report [results file name] [output .md name]

Defaults: part2_chat_suite/results_live_check.json -> LLM_LIVE_CHECK.md. Every row
is what the agent actually replied to the request (no editing), plus the plan the
LLM returned and the checks the suite ran on the resulting audio/state.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from evals.eval_chat_suite import CASES  # noqa: E402

RES = ROOT / "evals" / "results" / "part2_chat_suite"


def setup_text(setup) -> str:
    if not setup:
        return "fresh track"
    parts = []
    for st in setup:
        if isinstance(st, list) and st and st[0] == "chat":
            parts.append(f"after saying “{st[1]}”")
        else:
            ops = st if isinstance(st, list) else [st]
            parts.append("after " + ", ".join(
                f"{type(o).__name__.lower()} {o.range.unit} {o.range.start}–{o.range.end}" for o in ops))
    return "; ".join(parts)


def plan_text(plan) -> str:
    if not plan:
        return "—"
    ops = plan.get("ops") or []
    s = plan["action"]
    if ops:
        s += ": " + "; ".join(
            f"{o['op']} {o['range'].get('unit')} "
            + (f"last {o['range']['last']}" if o["range"].get("last") else
               f"{o['range'].get('start')}→{o['range'].get('end')}")
            + "".join(f" {k}={o[k]}" for k in ("total_plays", "direction", "db") if o.get(k) is not None)
            + (f" to {o['to']['unit']} {o['to'].get('index')}" if o.get("to") else "")
            for o in ops)
    if plan.get("sync"):
        s += f": A bar {plan['sync'].get('a_bar')} ← B bar {plan['sync'].get('b_bar')}, {plan['sync'].get('duration_s')} s"
    return s


def main():
    src = sys.argv[1] if len(sys.argv) > 1 else "results_live_check.json"
    dst = sys.argv[2] if len(sys.argv) > 2 else "LLM_LIVE_CHECK.md"
    rows = json.loads((RES / src).read_text(encoding="utf-8"))
    setups = {c[0]: (c[2], c[3]) for c in CASES}
    done = [r for r in rows if "pass" in r]
    n_pass = sum(r["pass"] for r in done)
    n_llm = sum(not r.get("offline_fallback") for r in done)
    models = sorted({r.get("llm_model") or "—" for r in done})
    L = [f"# Live LLM check — prompts and outputs\n",
         f"Source: `evals/results/part2_chat_suite/{src}` (generated by `python -m evals.llm_check_report`).\n",
         f"**{n_pass}/{len(done)} passed**; answered by the LLM: {n_llm}/{len(done)} (model: {', '.join(models)}); "
         "every reply below is verbatim. *Pass* means the resulting track state matched the intended edit "
         "(or, for refusals and questions, nothing changed and the reply stated the measured fact).\n",
         "| # | Track | Situation | Request | LLM plan | Result | Agent's reply |",
         "|---|---|---|---|---|---|---|"]
    for r in done:
        track, setup = setups.get(r["id"], (r.get("track"), []))
        reply = r["reply"].replace("|", "/").replace("\n", "<br>")
        fails = [k for k, v in (r.get("checks") or {}).items() if v is False]
        res = "✅ pass" if r["pass"] else f"❌ FAIL ({', '.join(fails)})"
        if r.get("offline_fallback"):
            res += " (offline parser)"
        if r.get("repair_round"):
            res += f"<br>repair round: {r['repair_round'][:60]}"
        L.append(f"| {r['id']} | {track} | {setup_text(setup)} | “{r['say']}” | {plan_text(r.get('plan'))} | {res} | {reply} |")
    (RES / dst).write_text("\n".join(L) + "\n", encoding="utf-8")
    print(f"wrote {(RES / dst).relative_to(ROOT)}  ({n_pass}/{len(done)} pass)")


if __name__ == "__main__":
    main()
