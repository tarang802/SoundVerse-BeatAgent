"""Compact listening evidence for reviewers: evals/evidence/*.mp3 + index.md.

    python -m evals.export_evidence

The brief asks reviewers to listen to the click auditions and renders. The full-quality
WAVs are regenerated by the evals (and git-ignored: ~1 GB); this writes small MONO MP3
copies of the ones that matter. Everything here is SYNTHETIC (generated test material)
-- no third-party music. Sources (must exist; run the evals first):
  Part 1  click auditions A1-A7          evals/results/part1_substitute_beat_this/*.click.wav
  Part 1  sync A7 -> A1 @ bar 33         evals/results/sync_A1_A7/*_mix.wav (all 4 methods)
  Part 2  edited audio, brief sessions   evals/results/part2_sessions/session_*/turnN.wav (last turn)
  Part 3  original clip + offline render data/p3/P*.wav, evals/results/part3/P*/render.wav
"""
from __future__ import annotations

import sys
from pathlib import Path

import numpy as np
import soundfile as sf

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from beatagent.audio_io import load, to_mono  # noqa: E402

RES = ROOT / "evals" / "results"
OUT = ROOT / "evals" / "evidence"
LEVEL = 0.9          # libsndfile MP3 compression level (0 best .. 1 smallest)


def mp3(src: Path, dst: Path) -> dict:
    audio, fmt = load(src)
    y = to_mono(audio).astype(np.float32)[:, None]
    dst.parent.mkdir(parents=True, exist_ok=True)
    with sf.SoundFile(str(dst), "w", fmt.sr, 1, format="MP3", subtype="MPEG_LAYER_III",
                      compression_level=LEVEL, bitrate_mode="CONSTANT") as f:
        f.write(y)
    return {"file": dst.relative_to(OUT).as_posix(), "from": src.relative_to(ROOT).as_posix(),
            "seconds": round(len(y) / fmt.sr, 1), "kb": dst.stat().st_size // 1024}


def main():
    rows = []
    for p in sorted((RES / "part1_substitute_beat_this").glob("A*.click.wav")):
        rows.append(("Part 1 click audition (accented downbeats)", mp3(p, OUT / "part1" / f"{p.stem}.mp3")))
    for p in sorted((RES / "sync_A1_A7").glob("*_mix.wav")):
        note = " (used by the app)" if p.stem.startswith("constant_attack") else " (compared, not used)"
        rows.append(("Part 1 sync A7 -> A1 @ bar 33, method " + p.stem.replace("_mix", "") + note,
                     mp3(p, OUT / "part1" / f"sync_{p.stem}.mp3")))
    for d in sorted((RES / "part2_sessions").glob("session_*")):
        # edited audio keeps the input's format: A3 is FLAC, so session 5 writes .flac
        turns = [t for t in d.glob("turn*.*") if t.suffix in (".wav", ".flac") and not t.stem.endswith(".click")]
        turns.sort(key=lambda q: int(q.stem.replace("turn", "").split(".")[0]))
        if turns:
            rows.append((f"Part 2 brief {d.name}, audio after the last edited turn",
                         mp3(turns[-1], OUT / "part2" / f"{d.name}_{turns[-1].stem}.mp3")))
    for name in ("P1", "P2", "P3", "P4"):
        orig, ren = ROOT / "data" / "p3" / f"{name}.wav", RES / "part3" / name / "render.wav"
        if orig.exists():
            rows.append((f"Part 3 {name} original clip", mp3(orig, OUT / "part3" / f"{name}_original.mp3")))
        if ren.exists():
            rows.append((f"Part 3 {name} offline render of the generated page (2 loops)",
                         mp3(ren, OUT / "part3" / f"{name}_render.mp3")))
    L = ["# Listening evidence (SYNTHETIC material)\n",
         "Small mono MP3 copies for listening; full-quality WAVs are regenerated by the evals "
         "(`python run.py demo`). Regenerate this folder with `python -m evals.export_evidence`.\n",
         "| what | file | seconds | KB | from |", "|---|---|---|---|---|"]
    L += [f"| {w} | [{r['file']}]({r['file']}) | {r['seconds']} | {r['kb']} | `{r['from']}` |" for w, r in rows]
    total = sum(r["kb"] for _, r in rows)
    L.append(f"\n{len(rows)} files, {total / 1024:.1f} MB.")
    (OUT / "index.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print(f"wrote {len(rows)} files, {total / 1024:.1f} MB -> {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
